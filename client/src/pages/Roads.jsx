import { api } from '../api.js';
import { useAuth } from '../auth.jsx';
import MapView from '../components/MapView.jsx';
import { ErrorBox, Loading, Notice, Status, useAction, useAsync } from '../components/ui.jsx';

export default function Roads() {
  const { can } = useAuth();
  const roads = useAsync(() => api.get('/roads'), []);
  const act = useAction();
  const set = (e, status) => act.run(async () => { await api.patch(`/roads/edges/${e.code}`, { status }); roads.reload(); });
  const nameOf = (c) => roads.data.nodes.find((n) => n.code === c)?.name || c;
  const state = (e) => e.effectiveStatus || e.status;

  return (
    <>
      <header className="page-head"><div><h1>Road network</h1><p className="lede">Routing avoids closed segments and slows degraded ones. Status comes from administrator updates and active incident reports. Real-time conditions may differ.</p></div></header>
      <Notice>This is a simplified sample network for the demo districts. For real operations, replace it with OpenStreetMap-derived data.</Notice>
      <ErrorBox error={act.error} />
      {roads.loading ? <Loading /> : <ErrorBox error={roads.error} />}
      {roads.data && <>
        <section className="panel flush"><MapView roads={roads.data} height={380} /></section>
        <section className="panel"><table className="table compact"><thead><tr><th>Segment</th><th>Between</th><th>km</th><th>Status</th><th>Why</th><th /></tr></thead>
          <tbody>{roads.data.edges.map((e) => (
            <tr key={e.code}><td>{e.name}{e.autoGenerated && <span className="small warn-text"> (auto-linked: verify)</span>}</td><td className="small">{nameOf(e.from)} to {nameOf(e.to)}</td><td>{e.distanceKm}</td>
              <td><Status value={state(e) === 'open' ? 'delivered' : state(e) === 'closed' ? 'failed' : 'in_transit'} label={state(e)} /></td>
              <td className="small">{(e.disruptionReasons || []).join('; ')}</td>
              <td>{can('admin', 'coordinator', 'logistics') && ['open', 'degraded', 'closed'].filter((s) => s !== e.status).map((s) => <button key={s} className="btn small-btn" disabled={act.busy} onClick={() => set(e, s)}>Mark {s}</button>)}</td></tr>))}</tbody></table>
          <p className="small muted">Buttons set the administrator status. A report-driven closure stays in effect until the report is resolved.</p></section></>}
    </>
  );
}
