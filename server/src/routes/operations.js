import { Router } from 'express';
import { z } from 'zod';
import crypto from 'node:crypto';
import { AppError, notFound } from '../lib/errors.js';
import { asyncHandler, validate } from '../middleware/validate.js';
import { requireRole } from '../middleware/auth.js';
import { haversineKm, ROAD_CIRCUITY, round } from '../lib/geo.js';
import { applyDisruptions } from '../services/routing.js';
import { assessSupplier } from '../services/suppliers.js';
import { submitReport } from '../services/reports.js';
import { DEFAULT_ASSUMPTIONS } from '../data/seed.js';
import { loadData, reportInputSchema } from './helpers.js';

const inv = z.coerce.number().min(0).max(1e9);
const inventorySchema = z.object({ food: inv, water: inv, medicine: inv });

const supplierCreate = z.object({
  name: z.string().trim().min(2).max(120),
  type: z.string().trim().max(60).default('Supplier'),
  location: z.object({ lat: z.coerce.number().min(-90).max(90), lon: z.coerce.number().min(-180).max(180) }),
  contact: z.string().trim().max(60).optional().default(''),
  inventory: inventorySchema,
});
const supplierUpdate = z.object({
  name: z.string().trim().min(2).max(120).optional(),
  type: z.string().trim().max(60).optional(),
  contact: z.string().trim().max(60).optional(),
});

const assumptionsSchema = z.object({
  foodKgPerPersonPerDay: z.coerce.number().min(0.05).max(5),
  waterLPerPersonPerDay: z.coerce.number().min(1).max(50),
  medicineKitsPerPerson: z.coerce.number().min(0).max(1),
  planningDays: z.coerce.number().int().min(1).max(30),
  impactRate: z.object({ medium: z.coerce.number().min(0).max(1), high: z.coerce.number().min(0).max(1) }),
  uncertainty: z.coerce.number().min(0).max(0.9),
  riskThresholds: z.object({ medium: z.coerce.number().min(0.05).max(0.95), high: z.coerce.number().min(0.05).max(0.99) }),
  maxSupplierRadiusKm: z.coerce.number().min(10).max(5000),
  staleSupplierDays: z.coerce.number().int().min(1).max(365),
  dedupeWindowHours: z.coerce.number().min(1).max(168),
}).refine((a) => a.riskThresholds.medium < a.riskThresholds.high, { message: 'medium threshold must be lower than high', path: ['riskThresholds'] })
  .refine((a) => a.impactRate.medium <= a.impactRate.high, { message: 'medium impact rate cannot exceed high', path: ['impactRate'] });

export function operationsRoutes({ store, config }) {
  const r = Router();
  const audit = (req, action, details) => store.audit.insert({ action, user: { id: req.user.id, name: req.user.name, role: req.user.role }, details, at: new Date() });

  // ---- Regions (full, incl. local inventory) -------------------------------------------------------
  r.get('/regions', asyncHandler(async (_req, res) => res.json({ regions: await store.regions.find() })));

  r.patch('/regions/:code/inventory', requireRole('admin', 'coordinator', 'logistics'), validate(inventorySchema), asyncHandler(async (req, res) => {
    const region = await store.regions.findOne({ code: req.params.code.toUpperCase() });
    if (!region) throw notFound('Region');
    const updated = await store.regions.update(region.id, { localInventory: req.body });
    await audit(req, 'region.inventory.update', { region: region.code, inventory: req.body });
    res.json({ region: updated });
  }));

  // ---- Suppliers (restricted: admin / coordinator / logistics) ----------------------------------------
  const supplierAccess = requireRole('admin', 'coordinator', 'logistics');
  const withAssessment = (s, assumptions) => ({ ...s, assessment: assessSupplier(s, new Date(), assumptions.staleSupplierDays) });

  r.get('/suppliers', supplierAccess, asyncHandler(async (_req, res) => {
    const { suppliers, assumptions } = await loadData(store);
    res.json({ suppliers: suppliers.map((s) => withAssessment(s, assumptions)) });
  }));

  r.post('/suppliers', requireRole('admin', 'logistics'), validate(supplierCreate), asyncHandler(async (req, res) => {
    const code = `SUP-${crypto.randomBytes(3).toString('hex').toUpperCase()}`;
    const supplier = await store.suppliers.insert({ ...req.body, code, inventoryUpdatedAt: new Date() });
    // Put the supplier on the road graph: link it to its 2 nearest nodes (flagged for human verification).
    const nodes = await store.nodes.find();
    const node = await store.nodes.insert({ code, name: supplier.name, kind: 'supplier', lat: req.body.location.lat, lon: req.body.location.lon });
    const nearest = nodes.map((n) => ({ n, d: haversineKm(n, node) })).sort((a, b) => a.d - b.d).slice(0, 2);
    for (const [i, { n, d }] of nearest.entries()) {
      await store.edges.insert({ code: `E-${code}-${i + 1}`, from: code, to: n.code, name: `Auto-link ${supplier.name} to ${n.name} (verify)`, kind: 'road', speedKmh: 40, status: 'open', distanceKm: round(d * ROAD_CIRCUITY, 1), autoGenerated: true });
    }
    await audit(req, 'supplier.create', { code });
    const { assumptions } = await loadData(store);
    res.status(201).json({ supplier: withAssessment(supplier, assumptions), note: 'Road links were auto-generated from straight-line distance. Verify them in the road network view.' });
  }));

  r.put('/suppliers/:id', requireRole('admin', 'logistics'), validate(supplierUpdate), asyncHandler(async (req, res) => {
    const updated = await store.suppliers.update(req.params.id, req.body);
    if (!updated) throw notFound('Supplier');
    await audit(req, 'supplier.update', { code: updated.code });
    res.json({ supplier: updated });
  }));

  r.patch('/suppliers/:id/inventory', requireRole('admin', 'logistics'), validate(inventorySchema), asyncHandler(async (req, res) => {
    const updated = await store.suppliers.update(req.params.id, { inventory: req.body, inventoryUpdatedAt: new Date() });
    if (!updated) throw notFound('Supplier');
    await audit(req, 'supplier.inventory.update', { code: updated.code, inventory: req.body });
    const { assumptions } = await loadData(store);
    res.json({ supplier: withAssessment(updated, assumptions) });
  }));

  r.delete('/suppliers/:id', requireRole('admin'), asyncHandler(async (req, res) => {
    const s = await store.suppliers.findById(req.params.id);
    if (!s) throw notFound('Supplier');
    await store.suppliers.remove(s.id);
    const node = await store.nodes.findOne({ code: s.code });
    if (node) await store.nodes.remove(node.id);
    for (const e of await store.edges.find()) if (e.from === s.code || e.to === s.code) await store.edges.remove(e.id);
    await audit(req, 'supplier.delete', { code: s.code });
    res.status(204).end();
  }));

  // ---- Road network -------------------------------------------------------------------------------
  r.get('/roads', asyncHandler(async (_req, res) => {
    const [nodes, edges, reports] = await Promise.all([store.nodes.find(), store.edges.find(), store.reports.find({ status: 'active' })]);
    res.json({ nodes, edges: applyDisruptions(edges, reports) });
  }));

  r.patch('/roads/edges/:code', requireRole('admin', 'coordinator', 'logistics'), validate(z.object({ status: z.enum(['open', 'degraded', 'closed']) })), asyncHandler(async (req, res) => {
    const edge = await store.edges.findOne({ code: req.params.code });
    if (!edge) throw notFound('Road segment');
    const updated = await store.edges.update(edge.id, { status: req.body.status });
    await audit(req, 'road.status', { code: edge.code, status: req.body.status });
    res.json({ edge: updated });
  }));

  // ---- Emergency reports (staff view) -------------------------------------------------------------
  r.get('/reports', asyncHandler(async (req, res) => {
    const status = ['active', 'resolved'].includes(req.query.status) ? req.query.status : undefined;
    const list = await store.reports.find(status ? { status } : {}, { sort: { reportedAt: -1 }, limit: 200 });
    res.json({ reports: list });
  }));

  r.post('/reports', requireRole('admin', 'coordinator', 'logistics'), validate(reportInputSchema), asyncHandler(async (req, res) => {
    const data = await loadData(store);
    if (!data.regions.some((x) => x.code === req.body.regionCode)) throw new AppError(422, 'UNKNOWN_LOCATION', 'Please select a valid location.');
    if (req.body.edgeCode && !data.edges.some((e) => e.code === req.body.edgeCode)) throw new AppError(422, 'UNKNOWN_ROAD', 'Please select a valid road segment.');
    const { report, duplicate } = await submitReport(store, req.body, data.assumptions, new Date(), 'staff');
    res.status(duplicate ? 200 : 201).json({ report, duplicate });
  }));

  r.patch('/reports/:id', requireRole('admin', 'coordinator'), validate(z.object({ status: z.enum(['active', 'resolved']) })), asyncHandler(async (req, res) => {
    const updated = await store.reports.update(req.params.id, { status: req.body.status });
    if (!updated) throw notFound('Report');
    await audit(req, 'report.status', { id: updated.id, status: req.body.status });
    res.json({ report: updated });
  }));

  // ---- Planning assumptions -------------------------------------------------------------------------
  r.get('/settings/assumptions', asyncHandler(async (_req, res) => {
    const { assumptions } = await loadData(store);
    res.json({ assumptions, defaults: DEFAULT_ASSUMPTIONS });
  }));

  r.put('/settings/assumptions', requireRole('admin', 'coordinator'), validate(assumptionsSchema), asyncHandler(async (req, res) => {
    const row = await store.settings.findOne({ key: 'assumptions' });
    if (row) await store.settings.update(row.id, { value: req.body });
    else await store.settings.insert({ key: 'assumptions', value: req.body });
    await audit(req, 'settings.assumptions', req.body);
    res.json({ assumptions: req.body });
  }));

  // ---- Dashboard summary ---------------------------------------------------------------------------
  r.get('/dashboard/summary', asyncHandler(async (_req, res) => {
    const [plans, reports, edges, suppliers, { assumptions }] = await Promise.all([
      store.plans.find({}, { sort: { createdAt: -1 } }), store.reports.find({ status: 'active' }), store.edges.find(), store.suppliers.find(), loadData(store),
    ]);
    const closed = applyDisruptions(edges, reports).filter((e) => e.effectiveStatus === 'closed').length;
    const byStatus = plans.reduce((a, p) => ({ ...a, [p.status]: (a[p.status] || 0) + 1 }), {});
    const flagged = suppliers.filter((s) => assessSupplier(s, new Date(), assumptions.staleSupplierDays).quality !== 'ok').length;
    const latest = plans[0];
    res.json({
      plansByStatus: byStatus, planCount: plans.length, activeReports: reports.length, closedRoads: closed, suppliers: suppliers.length, flaggedSuppliers: flagged,
      latestPlan: latest && { id: latest.id, number: latest.number, title: latest.title, status: latest.status, createdAt: latest.createdAt, totals: latest.result?.totals },
    });
  }));

  r.get('/audit', requireRole('admin', 'coordinator'), asyncHandler(async (_req, res) => {
    res.json({ entries: await store.audit.find({}, { sort: { at: -1 }, limit: 100 }) });
  }));

  return r;
}
